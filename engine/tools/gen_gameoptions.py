"""Generate huragok/gameoptions_data.py from tests/data/game-options-probe.txt: the server program's own words.

After a Project Reclaimer release that adds or renames game options, probe again with tools/reprobe_gameoptions.py
(`mode-check` with one option at 99999 per game type, and `dedicated playlist show` on scratch playlists that
name every number), which writes a new tests/data/game-options-probe.txt, then run:  python tools/gen_gameoptions.py
"""
import re
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
PROBE = ENGINE / "tests" / "data" / "game-options-probe.txt"
OUT = ENGINE / "huragok" / "gameoptions_data.py"
text = PROBE.read_text(encoding="utf-8")
probed = re.search(r"server program (\d[\w.+-]*)", text.splitlines()[0])
VERSION = probed.group(1) if probed else "0.9.18"

ranges: dict[tuple[str, str], tuple[str, int, int]] = {}  # (mode, key) -> (label, low, high)
section = ""
for line in text.splitlines():
    if line.startswith("### "):
        section = line
        continue
    m = re.match(r"^(\S+)\s+(?:\[(\w+)\] )?Error: (.+?) must be (-?\d+)\.\.=(-?\d+)$", line)
    if m and "generic" in section or m and "trait keys" in section:
        key, _, label, low, high = m.groups()
        ranges[("*", key)] = (label, int(low), int(high))
        continue
    m2 = re.match(r"^(\w+)\s+(mode\.\w+)\s+Error: (.+?) must be (-?\d+)\.\.=(-?\d+)$", line)
    if m2:
        mode, key, label, low, high = m2.groups()
        ranges[(mode, key)] = (label, int(low), int(high))

enums: dict[tuple[str, str], list[tuple[int, str]]] = {}
for line in text.splitlines():
    m = re.match(r"^(\w+) (\S+) \[(.+?)\] (-?\d+)\.\.(-?\d+): (.+)$", line)
    if not m:
        continue
    mode, key, label, low, high, rest = m.groups()
    choices = []
    for part in rest.split(" | "):
        value, name = part.split("=", 1)
        choices.append((int(value), name))
    scope = mode if key.startswith("mode.") else "*"
    if key.startswith(("player.", "leader.")):
        key = "trait." + key.split(".", 1)[1]
        scope = "*"
    if key.startswith("teams.red_"):
        key = "teams.COLOUR_" + key.removeprefix("teams.red_")
    enums[(scope, key)] = choices


def entry(scope: str, key: str, lookup_key: str | None = None) -> str:
    label, low, high = ranges[(scope, lookup_key or key)]
    enum_key = key
    if key.startswith("player."):
        enum_key = "trait." + key.split(".", 1)[1]
    choices = enums.get((scope if key.startswith("mode.") else "*", enum_key))
    shown_key = key.split(".", 1)[1] if key.startswith("player.") else key
    return f"    ({shown_key!r}, {label!r}, {low}, {high}, {tuple(choices) if choices else None!r}),\n"


out = ['"""The game option catalogue: every key the server program accepts, its label, range and the meaning of\n',
       "every number. GENERATED by tools/gen_gameoptions.py from tests/data/game-options-probe.txt (probed\n",
       f"against the server program {VERSION} with `mode-check` and `dedicated playlist show`); re-probe with\n",
       'tools/reprobe_gameoptions.py after a release that adds or renames options, then regenerate. Each row:\n',
       '(key, label, low, high, choices or None).\n"""\n\n',
       "from __future__ import annotations\n\n"]

shared = [k for (s, k) in ranges if s == "*" and not k.startswith(("player.", "rules.", "teams."))]
out.append("SHARED = [\n")
for key in shared:
    out.append(entry("*", key))
out.append("]\n\n")

out.append("# Team characters: teams.<colour>_character_set and teams.<colour>_character, the same for every colour.\n")
out.append("TEAM_COLOURS = ('red', 'blue', 'green', 'orange', 'purple', 'gold', 'brown', 'pink')\n")
red_set = ranges[("*", "teams.red_character_set")]
red_char = ranges[("*", "teams.red_character")]
out.append(f"TEAM_CHARACTER_SET = ({red_set[1]}, {red_set[2]}, {tuple(enums[('*', 'teams.COLOUR_character_set')])!r})\n")
out.append(f"TEAM_CHARACTER = ({red_char[1]}, {red_char[2]}, {tuple(enums[('*', 'teams.COLOUR_character')])!r})\n\n")

out.append("TRAITS = [\n")
for (s, k) in ranges:
    if s == "*" and k.startswith("player."):
        out.append(entry("*", k))
out.append("]\n\n")

out.append("MODE_RULES = {\n")
modes = []
for (s, k) in ranges:
    if s != "*" and s not in modes:
        modes.append(s)
for mode in modes:
    out.append(f"    {mode!r}: [\n")
    for (s, k) in ranges:
        if s == mode:
            label, low, high = ranges[(s, k)]
            choices = enums.get((mode, k))
            out.append(f"        ({k!r}, {label!r}, {low}, {high}, {tuple(choices) if choices else None!r}),\n")
    out.append("    ],\n")
out.append("}\n")
OUT.write_text("".join(out), encoding="utf-8")
print(f"{len(shared)} shared, {sum(1 for (s, k) in ranges if k.startswith('player.'))} traits, "
      f"{sum(1 for (s, k) in ranges if s != '*')} mode rules in {len(modes)} modes")
